"""Evaluate every predictions file in results/preds with the same evaluator, write
results/results.md, results/summary.json, figures, and refresh the README results block.

    python -m docextract.report
"""
from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from .evaluate import read_preds, score  # noqa: E402
from .metrics import aggregate, coverage_at_risk, eval_doc, risk_coverage  # noqa: E402
from .schema import coerce  # noqa: E402
from .synth import build_all, load  # noqa: E402
from .validate import checks, repair  # noqa: E402

NOISE_SETS = ["test_id_n00", "test_id_n01", "test_id_n02", "test_id_n05"]
OOD_SETS = ["test_ood_layout_n02", "test_ood_lang_n02"]
NICE = {"test_id_n00": "ID, 0% noise", "test_id_n01": "ID, 1% noise", "test_id_n02": "ID, 2% noise",
        "test_id_n05": "ID, 5% noise", "test_ood_layout_n02": "OOD layout, 2%", "test_ood_lang_n02": "OOD language (ES), 2%"}


def fmt(x):
    return f"{100 * x:.1f}"


def discover(preds_dir: Path):
    out = defaultdict(dict)
    for f in sorted(preds_dir.glob("*__*.jsonl")):
        sysname, ts = f.stem.split("__", 1)
        out[sysname][ts] = f
    return out


def confidences(recs_by_id, docs, use_repair=True):
    """Return per-doc (model_conf, validator_score, critical_ok) on repaired predictions."""
    mc, vs, ok = [], [], {"critical_ok": [], "money_ok": []}
    for d in docs:
        rec = recs_by_id.get(d["id"], {})
        p = coerce(rec.get("pred")) if rec.get("pred") is not None else None
        if use_repair:
            p, _ = repair(p)
        mc.append(rec.get("confidence") if rec.get("confidence") is not None else 1.0)
        vs.append(checks(p)["score"] if p else 0.0)
        r = eval_doc(p, d["gold"])
        for k in ok:
            ok[k].append(r[k])
    return np.array(mc), np.array(vs), {k: np.array(v, float) for k, v in ok.items()}


def run(results="results", data="data"):
    R, D = Path(results), Path(data)
    if not (D / "test_id_n00.jsonl").exists():
        build_all(D)
    found = discover(R / "preds")
    gold = {ts: load(D / f"{ts}.jsonl") for ts in NOISE_SETS + OOD_SETS}
    summ: dict = {}
    # fair comparison: for each test set evaluate every system on the *intersection* of documents it predicted
    # (LLM runs are often limited to fewer docs than the CPU baselines)
    common = {}
    for ts in NOISE_SETS + OOD_SETS:
        sets = [set(read_preds(files[ts])) for files in found.values() if ts in files]
        common[ts] = set.intersection(*sets) if sets else set()
    for sysname, files in found.items():
        for ts, f in files.items():
            preds = read_preds(f)
            docs = [d for d in gold[ts] if d["id"] in common[ts]]
            raw = aggregate(score(preds, docs))
            rep = aggregate(score(preds, docs, use_repair=True))
            lat = np.mean([r.get("latency_s") or 0 for r in preds.values()])
            summ.setdefault(sysname, {})[ts] = {"raw": raw, "repair": rep, "latency_s": float(lat), "n": len(docs)}
    systems = sorted(summ)
    md = ["# Results (auto-generated by `python -m docextract.report`)\n",
          "Every system is scored by the same code on the same files. 'repair' = arithmetic verifier/repair layer applied "
          "to that system's raw output. Doc EM = all 7 scalar fields and all line items exactly right "
          "(very strict; also see field EM). 95% bootstrap CI in brackets for doc EM.\n"]
    for ts in NOISE_SETS + OOD_SETS:
        rows = [(s, summ[s][ts]) for s in systems if ts in summ[s]]
        if not rows:
            continue
        md += [f"\n## {NICE[ts]} (n={rows[0][1]['n']})\n",
               "| system | post-proc | doc EM [95% CI] | field EM (macro) | item F1 (strict) | hallucination | JSON valid | ms/doc |",
               "|---|---|---|---|---|---|---|---|"]
        for s, r in rows:
            for tag in ("raw", "repair"):
                a = r[tag]
                ci = a["doc_em_ci95"]
                md.append(f"| {s} | {tag} | {fmt(a['doc_em'])} [{fmt(ci[0])}-{fmt(ci[1])}] | {fmt(a['field_em_macro'])} | "
                          f"{fmt(a['item_f1_strict'])} | {fmt(a['hallucination_rate'])} | {fmt(a['json_valid'])} | "
                          f"{1000 * r['latency_s']:.1f} |" if tag == "raw" else
                          f"| {s} | +repair | {fmt(a['doc_em'])} [{fmt(ci[0])}-{fmt(ci[1])}] | {fmt(a['field_em_macro'])} | "
                          f"{fmt(a['item_f1_strict'])} | {fmt(a['hallucination_rate'])} | {fmt(a['json_valid'])} | - |")
    # ---- per-field breakdown at 2% noise
    ts = "test_id_n02"
    if all(ts in summ[s] for s in systems):
        md += ["\n## Per-field exact match, ID 2% noise (raw -> +repair)\n",
               "| system | vendor | invoice_no | date | currency | subtotal | tax | total |", "|---|---|---|---|---|---|---|---|"]
        for s in systems:
            r, p = summ[s][ts]["raw"], summ[s][ts]["repair"]
            md.append(f"| {s} | " + " | ".join(f"{fmt(r['em_' + k])} -> {fmt(p['em_' + k])}" for k in
                      ["vendor", "invoice_number", "date", "currency", "subtotal", "tax", "total"]) + " |")
    # ---- selective prediction
    md += ["\n## Selective prediction: can the system know when it is wrong?\n",
           "Two correctness definitions: *critical* = vendor, date, currency and total all exact; *money* = subtotal, tax "
           "and total all exact (the part arithmetic can verify). Predictions are repaired first. "
           "AURC = area under risk-coverage curve (lower is better); 'cov@5%' = share of documents that can be "
           "auto-processed while keeping error <= 5%. Random ordering has AURC = overall error rate.\n",
           "| test set | correct = | system | confidence signal | AURC | cov@5% risk | cov@1% risk | error rate (no abstain) |",
           "|---|---|---|---|---|---|---|---|"]
    rc_curves = {}
    for ts in ["test_id_n02", "test_id_n05"]:
        for s in systems:
            if ts not in found[s]:
                continue
            docs = [d for d in gold[ts] if d["id"] in common[ts]]
            mc, vs, oks = confidences(read_preds(found[s][ts]), docs)
            for okname, ok in oks.items():
                for name, c in [("model only", mc), ("validator only", vs), ("model x validator", mc * vs)]:
                    if name == "model only" and np.all(mc == 1.0):
                        continue
                    cov, risk, aurc = risk_coverage(c, ok)
                    if okname == "critical_ok":
                        rc_curves[(ts, s, name)] = (cov, risk)
                    md.append(f"| {NICE[ts]} | {okname.split('_')[0]} | {s} | {name} | {aurc:.4f} | "
                              f"{fmt(coverage_at_risk(cov, risk, .05))}% | {fmt(coverage_at_risk(cov, risk, .01))}% | "
                              f"{fmt(1 - ok.mean())}% |")
    # ---- LoRA sweep if present
    sweeps = sorted((R / "lora_sweep").glob("*.json")) if (R / "lora_sweep").exists() else []
    if sweeps:
        md += ["\n## LoRA configuration sweep (val subset)\n",
               "| run | rank | targets | trainable params | train time (s) | peak GPU mem (GB) | val field EM | val item F1 |",
               "|---|---|---|---|---|---|---|---|"]
        for f in sweeps:
            j = json.loads(f.read_text())
            md.append(f"| {f.stem} | {j.get('rank')} | {j.get('targets')} | {j.get('trainable_params')} | "
                      f"{j.get('train_time_s')} | {j.get('peak_mem_gb')} | {j.get('val_field_em')} | {j.get('val_item_f1')} |")
    (R / "results.md").write_text("\n".join(md) + "\n")
    (R / "summary.json").write_text(json.dumps(summ, indent=2))
    make_figures(R, summ, systems, rc_curves)
    inject_readme(Path("README.md"), "\n".join(md))
    return summ


def make_figures(R: Path, summ, systems, rc_curves):
    fig_dir = R / "figures"
    fig_dir.mkdir(exist_ok=True)
    xs = [0, 1, 2, 5]
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.8))
    for s in systems:
        if not all(ts in summ[s] for ts in NOISE_SETS):
            continue
        for tag, ls in (("raw", "-"), ("repair", "--")):
            ax[0].plot(xs, [100 * summ[s][ts][tag]["field_em_macro"] for ts in NOISE_SETS], ls, marker="o",
                       label=f"{s} {'+repair' if tag == 'repair' else ''}".strip())
            ax[1].plot(xs, [100 * summ[s][ts][tag]["item_f1_strict"] for ts in NOISE_SETS], ls, marker="o")
    ax[0].set_title("Field EM (macro) vs OCR noise"); ax[1].set_title("Line-item F1 (strict) vs OCR noise")
    for a in ax:
        a.set_xlabel("per-character noise (%)"); a.set_ylabel("%"); a.grid(alpha=.3)
    ax[0].legend(fontsize=7)
    fig.tight_layout(); fig.savefig(fig_dir / "noise_robustness.png", dpi=150); plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 3.8))
    w = 0.8 / max(len(systems), 1)
    for i, s in enumerate(systems):
        vals = [100 * summ[s][ts]["repair"]["field_em_macro"] if ts in summ[s] else 0 for ts in ["test_id_n02"] + OOD_SETS]
        ax.bar(np.arange(3) + i * w, vals, w, label=s)
    ax.set_xticks(np.arange(3) + w * (len(systems) - 1) / 2)
    ax.set_xticklabels(["in-distribution\n(2% noise)", "unseen layout", "unseen language"])
    ax.set_ylabel("field EM, +repair (%)"); ax.set_title("Generalisation to unseen layouts / languages"); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig(fig_dir / "ood_generalisation.png", dpi=150); plt.close(fig)

    fig, ax = plt.subplots(figsize=(6, 4))
    for (ts, s, name), (cov, risk) in rc_curves.items():
        if ts == "test_id_n02" and name in ("model x validator", "validator only"):
            ax.step(100 * cov, 100 * risk, where="post", label=f"{s}: {name}")
    ax.set_xlabel("coverage (% auto-processed)"); ax.set_ylabel("error rate on accepted (%)")
    ax.set_title("Risk-coverage, ID 2% noise"); ax.grid(alpha=.3); ax.legend(fontsize=7)
    fig.tight_layout(); fig.savefig(fig_dir / "risk_coverage.png", dpi=150); plt.close(fig)


def inject_readme(readme: Path, md: str):
    if not readme.exists():
        return
    txt = readme.read_text()
    block = "<!-- RESULTS:START -->\n" + md.replace("# Results (auto-generated by `python -m docextract.report`)", "") + "\n<!-- RESULTS:END -->"
    new = re.sub(r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", lambda m: block, txt, flags=re.S)
    readme.write_text(new)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--data", default="data")
    a = ap.parse_args()
    run(a.results, a.data)
    print("report written to", a.results)
